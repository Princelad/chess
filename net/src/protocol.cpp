TimeControl parseTimeControl(std::string_view tc)
{
    TimeControl out;

    // Every valid wire form has "base+increment"; anything else — including
    // the empty string — is the unlimited game.
    const auto plus = tc.find('+');
    if (plus == std::string_view::npos)
        return out;

    const std::string_view base = tc.substr(0, plus);
    const std::string_view increment = tc.substr(plus + 1);
    const auto digitsOnlyAll = [](std::string_view s) {
        return !s.empty() && std::all_of(s.begin(), s.end(),
                                         [](char c) { return c >= '0' && c <= '9'; });
    };
    if (!digitsOnlyAll(base) || !digitsOnlyAll(increment))
        return out;

    out.baseSeconds = std::stoll(std::string(base));
    out.incrementSeconds = std::stoll(std::string(increment));
    if (out.baseSeconds > 0 || out.incrementSeconds > 0)
        out.unlimited = false;
    return out;
}

std::string sanitizeVariant(std::string_view variant)
{
    // Exact match only — an alias, casing variation, or unknown future tag
    // degrades to the standard game rather than guessing.
    if (variant == Chess960Variant)
        return std::string(Chess960Variant);
    return {};
}

bool serialize(sf::Packet& packet, const ClientMessage& msg)
{
    packet << ProtocolVersion;
    return std::visit([&](auto&& m) { return writeClient(packet, m); }, msg);
}

bool serialize(sf::Packet& packet, const ServerMessage& msg)
{
    packet << ProtocolVersion;
    return std::visit([&](auto&& m) { return writeServer(packet, m); }, msg);
}

std::optional<ClientMessage> deserializeClient(sf::Packet& packet)
{
    uint8_t version = 0;
    packet >> version;
    if (!static_cast<bool>(packet) || version != ProtocolVersion)
        return std::nullopt;

    uint8_t tag = 0;
    packet >> tag;
    if (!static_cast<bool>(packet))
        return std::nullopt;

    switch (static_cast<ClientMsgType>(tag)) {
        case ClientMsgType::Join: {
            JoinMsg msg;
            packet >> msg.name >> msg.timeControl >> msg.variant;
            if (!static_cast<bool>(packet)) return std::nullopt;
            return msg;
        }
        case ClientMsgType::Move: {
            MoveMsg msg;
            packet >> msg.san;
            if (!static_cast<bool>(packet)) return std::nullopt;
            return msg;
        }
        case ClientMsgType::DrawOffer:
            return DrawOfferMsg{};
        case ClientMsgType::DrawAccept:
            return DrawAcceptMsg{};
        case ClientMsgType::DrawDecline:
            return DrawDeclineMsg{};
        case ClientMsgType::Resign:
            return ResignMsg{};
        case ClientMsgType::Chat: {
            ChatMsg msg;
            packet >> msg.text;
            if (!static_cast<bool>(packet)) return std::nullopt;
            return msg;
        }
        case ClientMsgType::Ping:
            return PingMsg{};
        case ClientMsgType::Login: {
            LoginMsg msg;
            packet >> msg.name >> msg.password;
            if (!static_cast<bool>(packet)) return std::nullopt;
            return msg;
        }
        case ClientMsgType::ArchiveRequest: {
            ArchiveRequestMsg msg;
            int32_t limit = 0;
            packet >> limit;
            if (!static_cast<bool>(packet)) return std::nullopt;
            if (!readFlag(packet, msg.mineOnly)) return std::nullopt;
            msg.limit = limit;
            return msg;
        }
        case ClientMsgType::ArchiveGet: {
            ArchiveGetMsg msg;
            packet >> msg.id;
            if (!static_cast<bool>(packet) || msg.id < 0) return std::nullopt;
            return msg;
        }
        case ClientMsgType::LeaderboardRequest: {
            LeaderboardRequestMsg msg;
            int32_t limit = 0;
            packet >> limit;
            if (!static_cast<bool>(packet)) return std::nullopt;
            msg.limit = limit;
            return msg;
        }
        case ClientMsgType::Resume: {
            ResumeMsg msg;
            packet >> msg.token;
            if (!static_cast<bool>(packet)) return std::nullopt;
            if (msg.token.empty() || msg.token.size() > MaxTokenLength)
                return std::nullopt;
            return msg;
        }
        case ClientMsgType::TakebackRequest:
            return TakebackRequestMsg{};
        case ClientMsgType::TakebackAccept:
            return TakebackAcceptMsg{};
        case ClientMsgType::TakebackDecline:
            return TakebackDeclineMsg{};
        case ClientMsgType::RematchRequest:
            return RematchRequestMsg{};
        case ClientMsgType::RematchAccept:
            return RematchAcceptMsg{};
        case ClientMsgType::RematchDecline:
            return RematchDeclineMsg{};
        default:
            return std::nullopt;
    }
}

std::optional<ServerMessage> deserializeServer(sf::Packet& packet)
{
    uint8_t version = 0;
    packet >> version;
    if (!static_cast<bool>(packet) || version != ProtocolVersion)
        return std::nullopt;

    uint8_t tag = 0;
    packet >> tag;
    if (!static_cast<bool>(packet))
        return std::nullopt;

    switch (static_cast<ServerMsgType>(tag)) {
        case ServerMsgType::Welcome: {
            WelcomeMsg msg;
            int color = 0;
            packet >> color >> msg.opponent >> msg.rating >> msg.deviation;
            if (!static_cast<bool>(packet)) return std::nullopt;
            if (!validColor(color)) return std::nullopt;
            if (!readFlag(packet, msg.rated)) return std::nullopt;
            packet >> msg.timeControl >> msg.resumeToken
                   >> msg.variant >> msg.startFen;
            if (!static_cast<bool>(packet)) return std::nullopt;
            msg.color = static_cast<Color>(color);
            return msg;
        }
        case ServerMsgType::OpponentJoined: {
            OpponentJoinedMsg msg;
            packet >> msg.name;
            if (!static_cast<bool>(packet)) return std::nullopt;
            return msg;
        }
        case ServerMsgType::OpponentLeft:
            return OpponentLeftMsg{};
        case ServerMsgType::Move: {
            ServerMoveMsg msg;
            packet >> msg.san >> msg.remainingMs;
            if (!static_cast<bool>(packet)) return std::nullopt;
            if (msg.remainingMs < 0) return std::nullopt;
            return msg;
        }
        case ServerMsgType::DrawOffer:
            return ServerDrawOfferMsg{};
        case ServerMsgType::DrawDecline:
            return ServerDrawDeclineMsg{};
        case ServerMsgType::GameOver: {
            GameOverMsg msg;
            int result = 0, reason = 0;
            packet >> result >> reason;
            if (!static_cast<bool>(packet)) return std::nullopt;
            if (!validResult(result) || !validReason(reason)) return std::nullopt;
            msg.result = static_cast<GameResult>(result);
            msg.reason = static_cast<GameOverReason>(reason);
            return msg;
        }
        case ServerMsgType::Chat: {
            ServerChatMsg msg;
            packet >> msg.name >> msg.text;
            if (!static_cast<bool>(packet)) return std::nullopt;
            return msg;
        }
        case ServerMsgType::Pong:
            return PongMsg{};
        case ServerMsgType::Error: {
            ErrorMsg msg;
            packet >> msg.message;
            if (!static_cast<bool>(packet)) return std::nullopt;
            return msg;
        }
        case ServerMsgType::Profile: {
            ProfileMsg msg;
            packet >> msg.name >> msg.rating >> msg.deviation;
            if (!static_cast<bool>(packet)) return std::nullopt;
            if (!readFlag(packet, msg.isGuest)) return std::nullopt;
            return msg;
        }
        case ServerMsgType::ArchiveList: {
            ArchiveListMsg msg;
            int32_t count = 0;
            packet >> count;
            if (!static_cast<bool>(packet) || count < 0 || count > MaxArchiveEntries)
                return std::nullopt;
            msg.games.reserve(static_cast<std::size_t>(count));
            for (int32_t i = 0; i < count; ++i) {
                ArchiveEntryMsg entry;
                packet >> entry.id >> entry.whiteName >> entry.blackName
                       >> entry.result >> entry.playedAt;
                if (!static_cast<bool>(packet)) return std::nullopt;
                if (!validResult(entry.result)) return std::nullopt;
                if (!readFlag(packet, entry.rated)) return std::nullopt;
                msg.games.push_back(std::move(entry));
            }
            return msg;
        }
        case ServerMsgType::ArchiveGame: {
            ArchiveGameMsg msg;
            packet >> msg.id >> msg.whiteName >> msg.blackName
                   >> msg.result >> msg.reason
                   >> msg.timeControl >> msg.startFen >> msg.sanMoves
                   >> msg.playedAt;
            if (!static_cast<bool>(packet)) return std::nullopt;
            if (!validResult(msg.result) || !validReason(msg.reason))
                return std::nullopt;
            if (!readFlag(packet, msg.rated)) return std::nullopt;
            return msg;
        }
        case ServerMsgType::LeaderboardList: {
            LeaderboardListMsg msg;
            int32_t count = 0;
            packet >> count;
            if (!static_cast<bool>(packet) || count < 0
                || count > MaxLeaderboardEntries)
                return std::nullopt;
            msg.players.reserve(static_cast<std::size_t>(count));
            for (int32_t i = 0; i < count; ++i) {
                LeaderboardEntryMsg entry;
                packet >> entry.name >> entry.rating >> entry.deviation
                       >> entry.wins >> entry.losses >> entry.draws;
                if (!static_cast<bool>(packet)) return std::nullopt;
                // Counters are never negative in the players table; any other
                // value means a corrupt or hostile packet.
                if (entry.wins < 0 || entry.losses < 0 || entry.draws < 0)
                    return std::nullopt;
                msg.players.push_back(std::move(entry));
            }
            return msg;
        }
        case ServerMsgType::ResumeState: {
            ResumeStateMsg msg;
            int color = 0;
            packet >> color >> msg.opponent >> msg.rating >> msg.deviation;
            if (!static_cast<bool>(packet)) return std::nullopt;
            if (!validColor(color)) return std::nullopt;
            if (!readFlag(packet, msg.rated)) return std::nullopt;
            int32_t count = 0;
            packet >> msg.timeControl >> msg.fen >> count;
            if (!static_cast<bool>(packet)) return std::nullopt;
            if (count < 0 || count > MaxResumeMoves) return std::nullopt;
            msg.sans.reserve(static_cast<std::size_t>(count));
            for (int32_t i = 0; i < count; ++i) {
                std::string san;
                packet >> san;
                if (!static_cast<bool>(packet)) return std::nullopt;
                msg.sans.push_back(std::move(san));
            }
            packet >> msg.whiteRemainingMs >> msg.blackRemainingMs;
            if (!static_cast<bool>(packet)) return std::nullopt;
            // Clocks never carry negative time on the wire.
            if (msg.whiteRemainingMs < 0 || msg.blackRemainingMs < 0)
                return std::nullopt;
            msg.color = static_cast<Color>(color);
            return msg;
        }
        case ServerMsgType::OpponentReconnecting: {
            OpponentReconnectingMsg msg;
            packet >> msg.graceSeconds;
            if (!static_cast<bool>(packet)) return std::nullopt;
            if (msg.graceSeconds < 0) return std::nullopt;
            return msg;
        }
        case ServerMsgType::OpponentResumed:
            return OpponentResumedMsg{};
        case ServerMsgType::TakebackRequest:
            return ServerTakebackRequestMsg{};
        case ServerMsgType::TakebackAccepted: {
            TakebackAcceptedMsg msg;
            int32_t count = 0;
            packet >> count;
            if (!static_cast<bool>(packet) || count < 0
                || count > MaxResumeMoves)
                return std::nullopt;
            msg.sans.reserve(static_cast<std::size_t>(count));
            for (int32_t i = 0; i < count; ++i) {
                std::string san;
                packet >> san;
                if (!static_cast<bool>(packet)) return std::nullopt;
                msg.sans.push_back(std::move(san));
            }
            return msg;
        }
        case ServerMsgType::TakebackDecline:
            return ServerTakebackDeclineMsg{};
        case ServerMsgType::RematchRequest:
            return ServerRematchRequestMsg{};
        case ServerMsgType::RematchDecline: {
            ServerRematchDeclineMsg msg;
            if (!readFlag(packet, msg.withdrawn)) return std::nullopt;
            return msg;
        }
        default:
            return std::nullopt;
    }
}

std::string debugString(const ClientMessage& msg)
{
    return std::visit([](auto&& m) -> std::string {
        using T = std::decay_t<decltype(m)>;
        if constexpr (std::is_same_v<T, JoinMsg>)
            return "Join{name=\"" + escape(m.name) + "\", tc=\""
                + escape(m.timeControl) + "\", variant=\""
                + escape(m.variant) + "\"}";
        else if constexpr (std::is_same_v<T, MoveMsg>)
            return "Move{san=\"" + escape(m.san) + "\"}";
        else if constexpr (std::is_same_v<T, DrawOfferMsg>)
            return "DrawOffer{}";
        else if constexpr (std::is_same_v<T, DrawAcceptMsg>)
            return "DrawAccept{}";
        else if constexpr (std::is_same_v<T, DrawDeclineMsg>)
            return "DrawDecline{}";
        else if constexpr (std::is_same_v<T, ResignMsg>)
            return "Resign{}";
        else if constexpr (std::is_same_v<T, ChatMsg>)
            return "Chat{text=\"" + escape(m.text) + "\"}";
        else if constexpr (std::is_same_v<T, PingMsg>)
            return "Ping{}";
        else if constexpr (std::is_same_v<T, LoginMsg>)
            // Never log the password itself.
            return "Login{name=\"" + escape(m.name) + "\", password=***}";
        else if constexpr (std::is_same_v<T, ArchiveRequestMsg>)
            return "ArchiveRequest{limit=" + std::to_string(m.limit)
                + (m.mineOnly ? ", mine}" : ", all}");
        else if constexpr (std::is_same_v<T, ArchiveGetMsg>)
            return "ArchiveGet{id=" + std::to_string(m.id) + "}";
        else if constexpr (std::is_same_v<T, LeaderboardRequestMsg>)
            return "LeaderboardRequest{limit=" + std::to_string(m.limit) + "}";
        else if constexpr (std::is_same_v<T, ResumeMsg>)
            // Not a password-scale secret, but keeping it out of the log
            // still avoids inviting third-party token replays.
            return "Resume{token=***}";
        else if constexpr (std::is_same_v<T, TakebackRequestMsg>)
            return "TakebackRequest{}";
        else if constexpr (std::is_same_v<T, TakebackAcceptMsg>)
            return "TakebackAccept{}";
        else if constexpr (std::is_same_v<T, TakebackDeclineMsg>)
            return "TakebackDecline{}";
        else if constexpr (std::is_same_v<T, RematchRequestMsg>)
            return "RematchRequest{}";
        else if constexpr (std::is_same_v<T, RematchAcceptMsg>)
            return "RematchAccept{}";
        else if constexpr (std::is_same_v<T, RematchDeclineMsg>)
            return "RematchDecline{}";
    }, msg);
}

std::string debugString(const ServerMessage& msg)
{
    return std::visit([](auto&& m) -> std::string {
        using T = std::decay_t<decltype(m)>;
        if constexpr (std::is_same_v<T, WelcomeMsg>)
            return "Welcome{color=" + std::string(colorStr(m.color))
                + ", opponent=\"" + escape(m.opponent) + "\", tc=\""
                + escape(m.timeControl) + "\", variant=\""
                + escape(m.variant) + "\", startFen=\""
                + escape(m.startFen) + "\"}";
        else if constexpr (std::is_same_v<T, OpponentJoinedMsg>)
            return "OpponentJoined{name=\"" + escape(m.name) + "\"}";
        else if constexpr (std::is_same_v<T, OpponentLeftMsg>)
            return "OpponentLeft{}";
        else if constexpr (std::is_same_v<T, ServerMoveMsg>)
            return "Move{san=\"" + escape(m.san) + "\", remainingMs="
                + std::to_string(m.remainingMs) + "}";
        else if constexpr (std::is_same_v<T, ServerDrawOfferMsg>)
            return "DrawOffer{}";
        else if constexpr (std::is_same_v<T, ServerDrawDeclineMsg>)
            return "DrawDecline{}";
        else if constexpr (std::is_same_v<T, GameOverMsg>)
            return "GameOver{" + std::string(resultStr(m.result)) + ", " + std::string(reasonStr(m.reason)) + "}";
        else if constexpr (std::is_same_v<T, ServerChatMsg>)
            return "Chat{name=\"" + escape(m.name) + "\", text=\"" + escape(m.text) + "\"}";
        else if constexpr (std::is_same_v<T, PongMsg>)
            return "Pong{}";
        else if constexpr (std::is_same_v<T, ErrorMsg>)
            return "Error{message=\"" + escape(m.message) + "\"}";
        else if constexpr (std::is_same_v<T, ProfileMsg>)
            return "Profile{name=\"" + escape(m.name) + "\", rating="
                + std::to_string(m.rating) + ", deviation=" + std::to_string(m.deviation)
                + (m.isGuest ? ", guest}" : ", registered}");
        else if constexpr (std::is_same_v<T, ArchiveListMsg>)
            return "ArchiveList{games=" + std::to_string(m.games.size()) + "}";
        else if constexpr (std::is_same_v<T, ArchiveGameMsg>)
            return "ArchiveGame{id=" + std::to_string(m.id) + ", White=\""
                + escape(m.whiteName) + "\", Black=\"" + escape(m.blackName)
                + "\", " + std::string(resultStr(static_cast<GameResult>(m.result)))
                + ", " + std::string(reasonStr(static_cast<GameOverReason>(m.reason)))
                + ", plies=" + std::to_string(m.sanMoves.empty()
                    ? 0 : std::count(m.sanMoves.begin(), m.sanMoves.end(), ' ') + 1) + "}";
        else if constexpr (std::is_same_v<T, LeaderboardListMsg>)
            return "LeaderboardList{players=" + std::to_string(m.players.size()) + "}";
        else if constexpr (std::is_same_v<T, ResumeStateMsg>)
            return "ResumeState{color=" + std::string(colorStr(m.color))
                + ", opponent=\"" + escape(m.opponent) + "\", tc=\""
                + escape(m.timeControl) + "\", plies=" + std::to_string(m.sans.size())
                + ", whites=" + std::to_string(m.whiteRemainingMs)
                + ", blacks=" + std::to_string(m.blackRemainingMs) + "}";
        else if constexpr (std::is_same_v<T, OpponentReconnectingMsg>)
            return "OpponentReconnecting{graceSeconds=" + std::to_string(m.graceSeconds) + "}";
        else if constexpr (std::is_same_v<T, OpponentResumedMsg>)
            return "OpponentResumed{}";
        else if constexpr (std::is_same_v<T, ServerTakebackRequestMsg>)
            return "TakebackRequest{}";
        else if constexpr (std::is_same_v<T, TakebackAcceptedMsg>)
            return "TakebackAccepted{plies=" + std::to_string(m.sans.size()) + "}";
        else if constexpr (std::is_same_v<T, ServerTakebackDeclineMsg>)
            return "TakebackDecline{}";
        else if constexpr (std::is_same_v<T, ServerRematchRequestMsg>)
            return "RematchRequest{}";
        else if constexpr (std::is_same_v<T, ServerRematchDeclineMsg>)
            return m.withdrawn ? "RematchDecline{withdrawn}"
                               : "RematchDecline{}";
    }, msg);
}

