std::string escape(const std::string& s)
{
    std::string out;
    out.reserve(s.size());
    for (char c : s) {
        switch (c) {
            case '\\':  out += "\\\\"; break;
            case '"':   out += "\\\""; break;
            case '\n':  out += "\\n"; break;
            case '\t':  out += "\\t"; break;
            default:    out += c; break;
        }
    }
    return out;
}

