bool writeServer(sf::Packet& packet, const ResumeStateMsg& msg)
{
    packet << static_cast<uint8_t>(ServerMsgType::ResumeState)
           << static_cast<int>(msg.color) << msg.opponent
           << msg.rating << msg.deviation;
    if (!writeFlag(packet, msg.rated))
        return false;
    packet << msg.timeControl << msg.fen
           << static_cast<int32_t>(msg.sans.size());
    for (const auto& san : msg.sans)
        packet << san;
    if (!static_cast<bool>(packet))
        return false;
    packet << msg.whiteRemainingMs << msg.blackRemainingMs;
    return static_cast<bool>(packet);
}

