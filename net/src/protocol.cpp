bool validColor(int v)
{
    return v == 0 || v == 1;
}

bool validResult(int v)
{
    return v >= 0 && v <= static_cast<int>(GameResult::Abort);
}

bool validReason(int v)
{
    return v >= 0 && v <= static_cast<int>(GameOverReason::Timeout);
}

