// Refuses absurd archive counts on deserialize: a corrupt or hostile packet
// must not allocate an unbounded vector before any content check.
constexpr int32_t MaxArchiveEntries = 100;

// Same guard for leaderboard rows (server clamps its replies to the same
// maximum, so a genuine reply can never trip this).
constexpr int32_t MaxLeaderboardEntries = 100;

// Same guard for the resumed game's SAN list (11.2): a real game stays far
// below this; server clamps its own replies to the same maximum.
constexpr int32_t MaxResumeMoves = 512;

// Token form guard: the server generates short hex tokens; anything longer
// than this on deserialize was not generated by any server.
constexpr int32_t MaxTokenLength = 64;

// Booleans travel as uint8_t 0/1 (never read a non-0/1 byte back).
bool writeFlag(sf::Packet& packet, bool value)
{
    packet << static_cast<uint8_t>(value ? 1 : 0);
    return static_cast<bool>(packet);
}

bool readFlag(sf::Packet& packet, bool& value)
{
    uint8_t flag = 0;
    packet >> flag;
    if (!static_cast<bool>(packet) || flag > 1)
        return false;
    value = flag != 0;
    return true;
}

